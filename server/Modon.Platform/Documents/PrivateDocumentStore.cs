namespace Modon.Platform.Documents;

/// <summary>
/// Storage for applicants' private documents. Unlike FormCMS assets (served publicly under /files),
/// these files are never mapped to a URL: they are read only through endpoints that check ownership.
/// </summary>
public interface IPrivateDocumentStore
{
    Task SaveAsync(string key, Stream content, CancellationToken ct);
    Stream? OpenRead(string key);
    void Delete(string key);
}

public sealed class LocalPrivateDocumentStore : IPrivateDocumentStore
{
    private readonly string _root;

    public LocalPrivateDocumentStore(string root)
    {
        _root = Path.GetFullPath(root);
        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string key, Stream content, CancellationToken ct)
    {
        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await using var file = new FileStream(path, FileMode.Create, FileAccess.Write, FileShare.None);
        await content.CopyToAsync(file, ct);
    }

    public Stream? OpenRead(string key)
    {
        var path = Resolve(key);
        return File.Exists(path) ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read) : null;
    }

    public void Delete(string key)
    {
        var path = Resolve(key);
        if (File.Exists(path)) File.Delete(path);
    }

    /// <summary>Keys are generated by the server, but resolve defensively so nothing escapes the root.</summary>
    private string Resolve(string key)
    {
        var path = Path.GetFullPath(Path.Combine(_root, key));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new InvalidOperationException("Invalid document key.");
        return path;
    }
}
